//! Minimal i18n (zh / en) — keys aligned with Python `i18n.py`.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Zh,
    En,
}

pub fn normalize_language(raw: &str) -> &'static str {
    let s = raw.trim().to_ascii_lowercase();
    if s.starts_with("zh") || s == "cn" || s == "zh_cn" || s == "zh-cn" {
        "zh"
    } else {
        "en"
    }
}

pub fn parse_lang(raw: &str) -> Lang {
    if normalize_language(raw) == "zh" {
        Lang::Zh
    } else {
        Lang::En
    }
}

